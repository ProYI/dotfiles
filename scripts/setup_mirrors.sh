#!/bin/bash
# 镜像源配置脚本 - 针对中国大陆环境优化

set -e

# 颜色输出
GREEN='\033[0;32m'
BLUE='\033[0;34m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
NC='\033[0m'

log_info() {
    echo -e "${BLUE}==>${NC} $1"
}

log_success() {
    echo -e "${GREEN}✓${NC} $1"
}

log_warning() {
    echo -e "${YELLOW}⚠${NC} $1"
}

log_error() {
    echo -e "${RED}✗${NC} $1"
}

# 备份原有镜像源配置
backup_sources() {
    local file="$1"
    if [ -f "$file" ]; then
        sudo cp "$file" "${file}.backup.$(date +%Y%m%d_%H%M%S)"
        log_success "已备份原有配置: $file"
    fi
}

# 配置 Arch Linux 镜像源
setup_arch_mirrors() {
    log_info "配置 Arch Linux 镜像源..."

    backup_sources "/etc/pacman.d/mirrorlist"

    # 使用阿里云、清华、中科大镜像
    cat <<'EOF' | sudo tee /etc/pacman.d/mirrorlist > /dev/null
##
## Arch Linux repository mirrorlist
## Generated by dotfiles setup script
##

## China - Aliyun
Server = https://mirrors.aliyun.com/archlinux/$repo/os/$arch

## China - Tsinghua
Server = https://mirrors.tuna.tsinghua.edu.cn/archlinux/$repo/os/$arch

## China - USTC
Server = https://mirrors.ustc.edu.cn/archlinux/$repo/os/$arch

## China - 163
Server = https://mirrors.163.com/archlinux/$repo/os/$arch

## China - Huawei
Server = https://repo.huaweicloud.com/archlinux/$repo/os/$arch
EOF

    # 配置 archlinuxcn 源
    if ! grep -q "\[archlinuxcn\]" /etc/pacman.conf; then
        log_info "添加 archlinuxcn 源..."
        cat <<'EOF' | sudo tee -a /etc/pacman.conf > /dev/null

[archlinuxcn]
Server = https://mirrors.tuna.tsinghua.edu.cn/archlinuxcn/$arch
EOF
    fi

    log_success "Arch Linux 镜像源配置完成"
}

# 配置 Ubuntu/Debian 镜像源
setup_ubuntu_mirrors() {
    log_info "配置 Ubuntu 镜像源..."

    backup_sources "/etc/apt/sources.list"

    # 获取 Ubuntu 版本代号
    local codename=$(lsb_release -cs)

    # 使用阿里云镜像
    cat <<EOF | sudo tee /etc/apt/sources.list > /dev/null
# 阿里云镜像源
deb https://mirrors.aliyun.com/ubuntu/ ${codename} main restricted universe multiverse
deb https://mirrors.aliyun.com/ubuntu/ ${codename}-updates main restricted universe multiverse
deb https://mirrors.aliyun.com/ubuntu/ ${codename}-backports main restricted universe multiverse
deb https://mirrors.aliyun.com/ubuntu/ ${codename}-security main restricted universe multiverse

# 清华镜像源（备用）
# deb https://mirrors.tuna.tsinghua.edu.cn/ubuntu/ ${codename} main restricted universe multiverse
# deb https://mirrors.tuna.tsinghua.edu.cn/ubuntu/ ${codename}-updates main restricted universe multiverse
# deb https://mirrors.tuna.tsinghua.edu.cn/ubuntu/ ${codename}-backports main restricted universe multiverse
# deb https://mirrors.tuna.tsinghua.edu.cn/ubuntu/ ${codename}-security main restricted universe multiverse
EOF

    log_success "Ubuntu 镜像源配置完成"
}

# 配置 Debian 镜像源
setup_debian_mirrors() {
